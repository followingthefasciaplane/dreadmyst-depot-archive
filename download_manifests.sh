STEAM_USER="${1:?Usage: $0 <steam_username>}"

mkdir -p "$OUTPUT_DIR"

# Login once interactively so you only need SteamGuard once.
# This caches the session for subsequent steamcmd calls.
echo "Logging in as '$STEAM_USER' (you may need to enter your SteamGuard code)..."
steamcmd +login "$STEAM_USER" +quit
if [ $? -ne 0 ]; then
    echo "Login failed. Exiting."
    exit 1
fi

echo ""
echo "Downloading ${#MANIFESTS[@]} manifests..."
echo "SteamCMD depot dir: $STEAM_DIR"
echo "Output dir: $OUTPUT_DIR"
echo ""

for MANIFEST in "${MANIFESTS[@]}"; do
    DEST="$OUTPUT_DIR/$MANIFEST"

    if [ -d "$DEST" ]; then
        echo "[$MANIFEST] Already exists, skipping."
        continue
    fi

    echo "[$MANIFEST] Downloading..."
    steamcmd +login "$STEAM_USER" +download_depot "$APP_ID" "$DEPOT_ID" "$MANIFEST" +quit

    if [ -d "$STEAM_DIR" ]; then
        mv "$STEAM_DIR" "$DEST"
        echo "[$MANIFEST] Saved to $DEST"
    else
        echo "[$MANIFEST] ERROR: Download dir not found at $STEAM_DIR"
    fi

    echo ""
done

